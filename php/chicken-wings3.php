		<div class="steps">
			<p class="instruction">
				Procedure:
			</p>
	
			<ol>
				<li class="procedure-item">
					Divide the wings into 3 parts. Separate the drumette from the wingette. 
					Cut off the wingtip and set aside. Note: we'll only be using the big parts.
				</li>
				<li class="procedure-item">
					Pat the wings dry with paper towel and arrange inside an air fryer. 
					Air fry one side for 12 minutes at 350F. Do the same with the opposite side.
				</li>					
				<li class="procedure-item">
					Make the sauce by melting butter in a microwave oven. Add the hot sauce and stir until well blended.
				</li>
				<li class="procedure-item">
					Soak chicken wings in the sauce. Make sure that each piece is fully coated.
				</li>
				<li class="procedure-item">
					Serve with ranch dressing, carrots, and celery.
				</li>
				<li class="procedure-item">
					Share and enjoy!
				</li>
			</ol>
