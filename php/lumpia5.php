		<div class = "ingre">
			<h2 class="headline">
				Ingredients:
			</h2>

			<ul class="ingre-info">
				<li class="ingredients-item">
					50 pieces lumpia wrapper
				</li>
				<li class="ingredients-item">
					3 cups cooking oil
				</li>
				<li class="ingredients-item">
					1 1/2 lbs ground pork/chicken
				</li>
				<li class="ingredients-item">
					2 pieces onion minced
				</li>
				<li class="ingredients-item">
					2 pieces carrots minced
				</li>
				<li class="ingredients-item">
					1 1/2 teaspoons garlic powder
				</li>
				<li class="ingredients-item">
					1/2 teaspoon ground black pepper
				</li>
				<li class="ingredients-item">
					1/2 cup parsley chopped
				</li>
				<li class="ingredients-item">
					1 1/2 teaspoons salt
				</li>
				<li class="ingredients-item">
					1 tablespoon sesame oil
				</li>
				<li class="ingredients-item">
					1 tablespoon sesame oil
				</li>
			</ul>
		</div>
	
		<div class="steps">
			<p class="instruction">
				Procedure:
			</p>
	
			<ol>
				<li class="procedure-item">
					Combine all filling ingredients in a bowl. Mix well.
				</li>
				<li class="procedure-item">
					Scoop around 1 to 1 1/2 tablespoons of filling and place over a piece of lumpia wrapper. Spread the filling and then fold both sides of the wrapper. Fold the bottom. 
					Brush beaten egg mixture on the top end of the wrapper. Roll-up until completely wrapped. Perform the same step until all mixture are consumed.
				</li>
				<li class="procedure-item">
					Heat oil in a cooking pot. Deep fry lumpia in medium heat until it floats.
				</li>
				<li class="procedure-item">
					Remove from the pot. Let excess oil drip.
				</li>
				<li class="procedure-item">
					Share and enjoy!
				</li>
			</ol>
		</div>
	</div>